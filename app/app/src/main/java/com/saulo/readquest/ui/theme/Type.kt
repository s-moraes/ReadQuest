private fun TextStyle.scale(scale: Float): TextStyle {
    return copy(
        fontSize = if (fontSize.isSpecified) fontSize * scale else fontSize,
        lineHeight = if (lineHeight.isSpecified) lineHeight * scale else lineHeight
    )
}

fun scaledTypography(base: Typography, fontScale: Float): Typography {
    if (fontScale == 1.0f) return base
    return Typography(
        displayLarge = base.displayLarge.scale(fontScale),
        displayMedium = base.displayMedium.scale(fontScale),
        displaySmall = base.displaySmall.scale(fontScale),
        headlineLarge = base.headlineLarge.scale(fontScale),
        headlineMedium = base.headlineMedium.scale(fontScale),
        headlineSmall = base.headlineSmall.scale(fontScale),
        titleLarge = base.titleLarge.scale(fontScale),
        titleMedium = base.titleMedium.scale(fontScale),
        titleSmall = base.titleSmall.scale(fontScale),
        bodyLarge = base.bodyLarge.scale(fontScale),
        bodyMedium = base.bodyMedium.scale(fontScale),
        bodySmall = base.bodySmall.scale(fontScale),
        labelLarge = base.labelLarge.scale(fontScale),
        labelMedium = base.labelMedium.scale(fontScale),
        labelSmall = base.labelSmall.scale(fontScale)
    )
}
